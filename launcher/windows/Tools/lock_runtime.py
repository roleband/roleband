"""Lock the Windows x64 app's CPython 3.12 runtime to hashed wheels, and the release workflow's signing tools to
the same wheels."""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
#: What identity.py and release.py need beyond the standard library: cryptography and what it depends on.
SIGNING_PACKAGES = ("cffi", "cryptography", "pycparser")


def signing_lines(lines):
    """The runtime lock's own lines for the signing tools, so the job that holds the signing secrets installs only
    wheels the app already ships."""
    return [line for line in lines if line.split("==", 1)[0].lower() in SIGNING_PACKAGES]


def lock_lines(report):
    lines = []
    for item in report["install"]:
        name, version = item["metadata"]["name"], item["metadata"]["version"]
        info = item["download_info"]
        digest = info.get("archive_info", {}).get("hashes", {}).get("sha256")
        if not info["url"].endswith(".whl") or not digest:
            raise ValueError(f"{name} is not a hashed wheel")
        lines.append(f"{name}=={version} --hash=sha256:{digest}")
    return sorted(lines, key=str.lower)


def main():
    if sys.platform != "win32" or sys.version_info[:2] != (3, 12):
        raise ValueError("Resolve the runtime lock on Windows with CPython 3.12")
    with tempfile.TemporaryDirectory(prefix="roleband-windows-lock-") as directory:
        report = Path(directory) / "report.json"
        subprocess.run([
            sys.executable, "-m", "pip", "--isolated", "install", "--disable-pip-version-check",
            "--dry-run", "--ignore-installed", "--only-binary=:all:", "--quiet",
            "--report", str(report), "--target", str(Path(directory) / "target"),
            "-c", str(ROOT / "backend/constraints/windows-x86_64.txt"),
            "-r", str(ROOT / "backend/requirements.txt"), "setuptools",
        ], check=True)
        lines = lock_lines(json.loads(report.read_text(encoding="utf-8")))
    lock = ROOT / "launcher/windows/runtime-lock.txt"
    lock.write_text(
        "# CPython 3.12, Windows x64. Generated by Tools/lock_runtime.py from\n"
        "# backend/requirements.txt and backend/constraints/windows-x86_64.txt.\n"
        + "\n".join(lines) + "\n", encoding="utf-8")
    signing = ROOT / "launcher/windows/signing-requirements.txt"
    signing.write_text(
        "# What .github/workflows/windows-release.yml installs to sign: runtime-lock.txt's own lines.\n"
        "# Generated by Tools/lock_runtime.py.\n"
        + "\n".join(signing_lines(lines)) + "\n", encoding="utf-8")
    print(lock)
    print(signing)


if __name__ == "__main__":
    main()
