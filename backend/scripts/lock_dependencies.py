"""Regenerate `backend/constraints/<platform>.txt`: the whole install graph, pinned.

`requirements.txt` and `requirements-dev.txt` pin what we ask for. Everything
those packages pull in was chosen by pip at install time, so two machines
installing the same files could run different code. A constraints file pins the
rest, and every install path passes the one for its platform with `-c`:
`setup.sh`, `deploy/install.sh` and the backend/contract-drift workflows.

Per platform, not universal, on purpose. A universal resolve covers every Python
the resolver can imagine, and one platform this project does not run on with no
solution fails it for all of them.
The supported set is exactly `PLATFORMS`; `setup.sh` refuses any other, and
`tests/test_dependency_lock.py` checks every file here against the requirements.

The existing file is read as PREFERENCES, so regenerating keeps every version it
can and moves only what a requirements change forces. Upgrades are deliberate:

    .venv/bin/python -m scripts.lock_dependencies
    .venv/bin/python -m scripts.lock_dependencies --upgrade-package httpx

Needs `uv` on PATH. It is the resolver, not a dependency of the app: nothing
installs or imports it, and `pip install -c` consumes what it writes.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND.parent
CONSTRAINTS_DIR = BACKEND / "constraints"
#: Every file the locks resolve. `requirements-optional.txt` is here although
#: nothing installs it by default: an optional package must still be PINNED
#: when someone does install it.
REQUIREMENTS = ("requirements.txt", "requirements-dev.txt", "requirements-optional.txt")


@dataclass(frozen=True)
class Platform:
    target: str
    #: Linux resolves binary-only: every pin must install from a published wheel,
    #: so a runner never compiles a native extension. macOS cannot, because
    #: `apple-fm-sdk` publishes an sdist.
    only_binary: bool
    env: dict[str, str] = field(default_factory=dict)


PLATFORMS: dict[str, Platform] = {
    # onnxruntime 1.28 publishes macosx_14_0_arm64 wheels only; uv's default
    # macOS target is 13.0, which finds no wheel and fails the resolve.
    "macos-arm64": Platform("aarch64-apple-darwin", False, {"MACOSX_DEPLOYMENT_TARGET": "14.0"}),
    # CI runs here (ubuntu-24.04).
    "linux-x86_64": Platform("x86_64-manylinux_2_28", True),
    # Install rehearsals run here (ubuntu:24.04 on Apple silicon).
    "linux-aarch64": Platform("aarch64-manylinux_2_28", True),
}

HEADER = (
    "# The full install graph for {name} ({target}), Python {python}. Generated by\n"
    "# `.venv/bin/python -m scripts.lock_dependencies` from requirements.txt and\n"
    "# requirements-dev.txt; do not edit by hand. Install with both -r files and\n"
    "# `-c constraints/{name}.txt`.\n"
)


def python_version() -> str:
    return (REPO_ROOT / ".python-version").read_text().strip()


def lock(name: str, upgrade: list[str]) -> Path:
    platform = PLATFORMS[name]
    out = CONSTRAINTS_DIR / f"{name}.txt"
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / out.name
        if out.exists():
            shutil.copyfile(out, work)  # preferences: keep what still resolves
        cmd = [
            "uv", "pip", "compile", "--quiet", "--no-header",
            "--python-version", python_version(),
            "--python-platform", platform.target,
            *(f"--upgrade-package={pkg}" for pkg in upgrade),
            *(["--only-binary", ":all:"] if platform.only_binary else []),
            *(str(BACKEND / req) for req in REQUIREMENTS),
            "-o", str(work),
        ]
        subprocess.run(cmd, check=True, cwd=BACKEND, env={**os.environ, **platform.env})
        body = work.read_text()
    header = HEADER.format(name=name, target=platform.target, python=python_version())
    out.write_text(header + body)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--upgrade-package", action="append", default=[], metavar="NAME")
    parser.add_argument("--platform", action="append", choices=sorted(PLATFORMS))
    args = parser.parse_args(argv)
    if shutil.which("uv") is None:
        print("uv is not on PATH; install it (brew install uv) to regenerate locks", file=sys.stderr)
        return 2
    CONSTRAINTS_DIR.mkdir(exist_ok=True)
    for name in args.platform or PLATFORMS:
        print(f"{name}: {lock(name, args.upgrade_package).relative_to(BACKEND)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
