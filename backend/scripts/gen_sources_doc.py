"""Generate `docs/sources.md` from the source review register.

One row per listing adapter in `ADAPTER_REGISTRY`, read from its
`SOURCE_REVIEWS` entry (`tracker/source_review.py`): how RoleBand reaches the
source, the robots verdict for the route it requests, whether the source is
walled or user-directed, the User-Agent it sends and the fetch tier it needs.
The output is deterministic (rows sorted by provider key, no timestamps), so
the committed file is a pure function of the register.

The script only reads the register. It decides nothing and gates nothing:
`source_policy.collection_access` stays the single decision point.

Run:  .venv/bin/python -m scripts.gen_sources_doc [--check]

`--check` renders into memory and compares with the committed file, exiting 1
on any difference. `tests/test_sources_doc.py` runs the same comparison.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Mapping
from pathlib import Path
from urllib.parse import urlsplit

from tracker.connectors import ADAPTER_REGISTRY
from tracker.source_review import (
    SOURCE_REVIEWS,
    AccessClass,
    FetchTier,
    RobotsStatus,
    SourceReview,
    Wall,
)

OUT = Path(__file__).resolve().parents[2] / "docs" / "sources.md"
COMMAND = "cd backend && .venv/bin/python -m scripts.gen_sources_doc"

_ACCESS = {
    AccessClass.PUBLIC_API: "documented public API",
    AccessClass.PUBLIC_FEED: "structured public feed",
    AccessClass.UNDOCUMENTED_ENDPOINT: "undocumented endpoint",
    AccessClass.HTML_EXTRACTION: "HTML extraction",
    AccessClass.BROWSER_AUTOMATION: "browser automation",
}

_ROBOTS = {
    RobotsStatus.ALLOWED: "allowed",
    RobotsStatus.DISALLOWED: "disallowed",
    RobotsStatus.NOT_SERVED: "no robots file served",
    RobotsStatus.UNVERIFIED: "not read",
}

_WALL = {
    Wall.ROBOTS: "walled (robots)",
    Wall.BOT_WALL: "walled (bot wall)",
}

_TIER = {
    FetchTier.IDENTIFIED: "default client",
    FetchTier.BROWSER_IDENTITY: "browser headers",
    FetchTier.TLS_FINGERPRINT: "browser TLS fingerprint",
    FetchTier.HEADLESS: "headless browser",
    FetchTier.PROXY: "headless browser via proxy",
}

PREAMBLE = f"""\
<!-- Generated by backend/scripts/gen_sources_doc.py. Do not edit. -->

# Sources

This file is generated from the source review register,
`backend/tracker/source_review.py`. Do not edit it by hand: change the
register, then run `{COMMAND}`. `backend/tests/test_sources_doc.py` fails when
this file and the register disagree.

## What a source review is

A source is one kind of careers site RoleBand reads, usually an applicant
tracking system that many employers share. Every listing adapter in
`ADAPTER_REGISTRY` (`backend/tracker/connectors/listing/__init__.py`) has a row
in `SOURCE_REVIEWS`, and `backend/tests/test_source_review.py` names any
adapter without one. A row records facts about the source: how RoleBand
reaches it, the exact route it requests, what the host's `robots.txt` says
about that route (with the file's hash and the rule that decided), and the
User-Agent RoleBand sends. The access class names a method, not a permission;
`unreviewed` is not approval, and approving a source approves no employer on
it. `python -m scripts.check_source_review` re-reads the robots evidence;
`--packaged` also rejects a source whose fetch tier needs a browser the Mac app
does not ship, and changes neither collection policy nor consent.

## How a request is decided

The register itself refuses nothing. `collection_access` in
`backend/tracker/source_policy.py` is the one place a request is refused: by
the operator deny list (`sync_policy_denied_providers`), or by a wall the user
has not consented to. Every collecting path names its company and passes its
consent. Reporting callers read `.denied`; executing callers call `.require()`,
which raises `CollectionPolicyDenied`, a local decision and never evidence that
a source failed.

Each board is read paced per host (`scraper_min_delay_seconds` in
`backend/tracker/config.py`), with retries that honour `Retry-After`. Within a
read a wait is capped at the retry policy's backoff; across runs the latest
`Retry-After` a source received (seconds or an HTTP date) holds every binding on
that provider until then, capped at `sync_provider_blocked_cooldown_seconds`. A
board that answers 404 is that company's, and pauses nothing else. A failed read
backs its provider off for `sync_provider_backoff_seconds`, doubled for each
later run that fails there, up to the blocked cooldown; a run counts once per
provider, however many of its companies failed there. A run that fails on its
own, an error of ours rather than a provider's answer, backs no provider off:
the companies it did not finish are due again after the same delay. Each source
run records its completed requests, retries and response bytes
(`scrape_source_runs`), or NULL when its reads never reached the shared
transports.

## Walled and user-directed sources

A source is **walled** when its `robots.txt` disallows the route RoleBand
requests, or when the host refuses the default client. A company
on a walled source is off by default and is never on the curated list.
RoleBand collects it only after the user follows that company and accepts a
warning that states the source's policy. The consent is stored with a
fingerprint of the wall the user was shown (`TrackedCompany.consent_fingerprint`,
written only by `company_store.record_consent`) as the record of what was
agreed. RoleBand asks once per company: the consent stands when the robots file,
the kind of wall or the fetch tier changes later, and when the user unfollows the
company and follows it again.

A **user-directed** source is not a wall, but the user directs each company on
it. Its companies are never curated. Following one opens a dialog whose single
answer follows the company and reads it at once, and whose checkbox, on by
default, says whether it is then scanned on the regular schedule. The answer is
stored like a consent, with the source's own fingerprint (`directed:`), which
unlocks no wall and no fetch tier. A company left to be read on request, or
followed before the dialog asked, is read when the user starts a scan; the
scheduler, the directory sweep and role discovery never read one that has no
agreement. One rule decides all of it (`source_policy.direction_wait`).

Only a walled source may record a fetch tier other than the default client,
and RoleBand uses that tier only for a company whose user consented. The tiers
are implemented in `backend/tracker/connectors/runtime/tiers.py`, and a block
is never retried with a stronger tier.

## Columns

- **Access**: how RoleBand reaches the source.
- **Listing request**: the HTTP method and host of the listing route.
  `{{host}}` stands for a tenant's own careers host.
- **Robots (listing route)**: the `robots.txt` verdict for that route, with
  the deciding rule when one matched.
- **Collection**: `default` (no wall), walled (and why), or user-directed.
- **User-Agent**: the value RoleBand sends.
- **Fetch tier**: how the request is made.

"""

_HEADER = (
    "| Source | Access | Listing request | Robots (listing route) | Collection"
    " | User-Agent | Fetch tier |\n"
    "|---|---|---|---|---|---|---|\n"
)


def _cell(text: str) -> str:
    """One Markdown table cell: no newline, no unescaped pipe."""
    return " ".join(text.split()).replace("|", "\\|")


def _code(text: str) -> str:
    return f"`{_cell(text)}`"


def listing_request(surface: str) -> str:
    """`GET boards-api.greenhouse.io` from the register's listing surface."""
    method, _, rest = surface.partition(" ")
    url = rest.split(" ", 1)[0]
    host = urlsplit(url).netloc or url
    return f"{method} {_code(host)}"


def robots_verdict(review: SourceReview) -> str:
    verdict = _ROBOTS[review.robots.status]
    rule = review.robots.winning_rule
    return f"{verdict} ({_code(rule)})" if rule else verdict


def collection(review: SourceReview) -> str:
    wall = review.wall
    if wall is not None:
        return _WALL[wall]
    if review.user_directed:
        return "user-directed"
    return "default"


def row(key: str, review: SourceReview) -> str:
    cells = (
        _code(key),
        _ACCESS[review.access_class],
        listing_request(review.listing_surface),
        robots_verdict(review),
        collection(review),
        _code(review.request_identity),
        _TIER[review.fetch_tier],
    )
    return "| " + " | ".join(cells) + " |\n"


def render(
    reviews: Mapping[str, SourceReview] | None = None,
    registry: Mapping[str, object] | None = None,
) -> str:
    """The full document. Raises when the registry and the register disagree."""
    reviews = SOURCE_REVIEWS if reviews is None else reviews
    registry = ADAPTER_REGISTRY if registry is None else registry
    missing = sorted(set(registry) - set(reviews))
    extra = sorted(set(reviews) - set(registry))
    if missing or extra:
        raise ValueError(
            f"register and ADAPTER_REGISTRY disagree: no row for {missing},"
            f" row without an adapter {extra}"
        )
    rows = "".join(row(key, reviews[key]) for key in sorted(registry))
    return PREAMBLE + _HEADER + rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument(
        "--check", action="store_true",
        help="compare with the committed file and exit 1 on any difference",
    )
    args = parser.parse_args(argv)

    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if current != text:
            print(f"{OUT.name} is out of date with the source register. Run: {COMMAND}")
            return 1
        print(f"{OUT.name} is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
